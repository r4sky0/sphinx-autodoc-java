"""Java source documentation in Sphinx, without importing application code."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
from urllib.parse import urlsplit

from sphinx.errors import ExtensionError
from sphinx.util import logging

from .domain import JavaDomain
from .extractor import VERSION, atomic_write, extract, read_model

__version__ = VERSION
LOGGER = logging.getLogger(__name__)
MARKER = ".. Generated by sphinx-java-autodoc; do not edit.\n\n"


def generate_pages(root, directory: Path, visibility: str) -> None:
    pages = {}
    entries = []
    for package in root.findall("package"):
        name = package.get("name", "")
        if not re.fullmatch(r"[\w.$]*", name):
            raise ExtensionError(f"Java autodoc: invalid package name {name!r}")
        types = [
            t
            for t in root.findall("type")
            if t.get("package") == name
            and (visibility == "protected" or t.get("visibility") == "public")
        ]
        if not types:
            continue
        filename = "package-" + (name or "default")
        entries.append(filename)
        title = name or "Default package"
        body = f"{title}\n{'=' * len(title)}\n\n"
        if name:
            body += f".. java:autopackage:: {name}\n\n"
        body += ".. toctree::\n   :maxdepth: 1\n\n"
        for t in types:
            symbol = t.get("id")
            if not re.fullmatch(r"[\w.$]+", symbol):
                raise ExtensionError(f"Java autodoc: invalid type name {symbol!r}")
            typefile = "type-" + symbol
            body += f"   {typefile}\n"
            pages[typefile + ".rst"] = (
                MARKER
                + f"{symbol}\n{'=' * len(symbol)}\n\n.. java:autoclass:: {symbol}\n   :members:\n"
            )
        pages[filename + ".rst"] = MARKER + body
    pages["index.rst"] = (
        MARKER
        + "Java API\n========\n\n.. toctree::\n   :maxdepth: 2\n\n"
        + "".join(f"   {entry}\n" for entry in entries)
    )
    manifest_path = directory / ".java-autodoc-manifest.json"
    try:
        old = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
        if not isinstance(old, dict):
            raise ValueError("expected a filename-to-hashes mapping")
        for filename, hashes in old.items():
            if isinstance(hashes, str):
                hashes = old[filename] = [hashes]
            if (
                Path(filename).name != filename
                or not filename.endswith(".rst")
                or not isinstance(hashes, list)
                or not hashes
                or any(
                    not isinstance(h, str) or not re.fullmatch(r"[0-9a-f]{64}", h)
                    for h in hashes
                )
            ):
                raise ValueError("invalid filename or content hash")
    except (OSError, ValueError) as exc:
        raise ExtensionError(
            f"Java autodoc: invalid generated-page manifest: {exc}"
        ) from exc
    # Check ownership before recording any new files as ours.
    for filename in old.keys() | pages.keys():
        path = directory / filename
        if path.exists() and hashlib.sha256(
            path.read_bytes()
        ).hexdigest() not in old.get(filename, []):
            raise ExtensionError(
                f"Java autodoc: refusing to overwrite edited or unowned page {path}; move your edits into a guide."
            )
    hashes = {
        name: hashlib.sha256(content.encode()).hexdigest()
        for name, content in pages.items()
    }
    pending = {name: set(values) for name, values in old.items()}
    for name, digest in hashes.items():
        pending.setdefault(name, set()).add(digest)
    # Journal both versions before any page changes, so an interrupted build can retry.
    atomic_write(
        manifest_path,
        json.dumps(
            {name: sorted(values) for name, values in sorted(pending.items())}
        ).encode(),
    )
    for filename, content in pages.items():
        atomic_write(directory / filename, content.encode())
    for filename in old.keys() - pages.keys():
        (directory / filename).unlink(missing_ok=True)
    atomic_write(manifest_path, json.dumps(hashes, indent=2, sort_keys=True).encode())


def prepare(app):
    config = app.config
    if config.java_visibility not in {"public", "protected"}:
        raise ExtensionError(
            "java_visibility must be 'public' or 'protected' (public plus protected)."
        )
    for prefix, url in config.java_external_javadoc.items():
        if not prefix or urlsplit(url).scheme not in {"http", "https"}:
            raise ExtensionError(
                "java_external_javadoc must map package prefixes to http(s) Javadoc roots."
            )
    base = Path(app.confdir)
    if config.java_model and config.java_sources:
        raise ExtensionError("Set either java_sources or java_model, not both.")
    if config.java_model:
        path = (base / config.java_model).resolve()
        root = read_model(path)
        fingerprint = hashlib.sha256(path.read_bytes()).hexdigest()
    elif config.java_sources:
        path, fingerprint = extract(
            [base / s for s in config.java_sources],
            [base / s for s in config.java_classpath],
            Path(app.doctreedir) / "java-cache",
            jdk=config.java_jdk,
            release=str(config.java_release),
        )
        root = read_model(path)
    else:
        # A consumer using only Java roles and intersphinx needs no local sources.
        import xml.etree.ElementTree as ET

        root = ET.Element("api", schema="1")
        path = base / "conf.py"
        fingerprint = "empty"
    app._java_changed = getattr(app.env, "java_fingerprint", None) != fingerprint
    app.env.java_fingerprint = fingerprint
    app.env.java_model = root
    app.env.java_model_path = str(path)
    app.env.java_references = {
        n.get("target"): dict(n.attrib) for n in root.iter("link")
    }
    for diagnostic in root.findall("diagnostic"):
        LOGGER.warning(diagnostic.text, type="java", subtype="extract")
    if config.java_generate:
        directory = (Path(app.srcdir) / config.java_generate).resolve()
        if (
            not directory.is_relative_to(Path(app.srcdir).resolve())
            or directory == Path(app.srcdir).resolve()
        ):
            raise ExtensionError(
                "java_generate must be a subdirectory of the Sphinx source directory."
            )
        if not root.findall("type"):
            raise ExtensionError(
                "Java autodoc: cannot generate API pages without extracted types."
            )
        generate_pages(root, directory, config.java_visibility)


def outdated(app, env, added, changed, removed):
    # Roles and missing-type directives also depend on the complete Java model.
    return sorted(env.found_docs - removed) if app._java_changed else []


def add_static_path(app):
    app.config.html_static_path.append(str(Path(__file__).parent / "static"))


def setup(app):
    for name, default in {
        "java_sources": [],
        "java_classpath": [],
        "java_jdk": "",
        "java_release": "",
        "java_model": "",
        "java_generate": "",
        "java_visibility": "protected",
        "java_external_javadoc": {},
    }.items():
        app.add_config_value(name, default, "env")
    app.add_domain(JavaDomain)
    app.add_css_file("java-autodoc.css")
    app.connect("builder-inited", add_static_path)
    app.connect("builder-inited", prepare)
    app.connect("env-get-outdated", outdated)
    return {
        "version": VERSION,
        "env_version": 2,
        "parallel_read_safe": True,
        "parallel_write_safe": True,
    }
