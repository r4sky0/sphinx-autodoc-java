"""Generated API pages: RST skeletons planned from the model and published safely."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re

from sphinx.errors import ExtensionError

from .extractor import atomic_write
from .model import MEMBER_GROUPS, TYPE_GROUPS, grouped, local_name, visible

MARKER = ".. Generated by sphinx-java-autodoc; do not edit.\n\n"


def heading(title: str, underline: str) -> str:
    return f"{title}\n{underline * len(title)}\n\n"


def summary_table(symbols) -> str:
    return ".. java:autosummary::\n\n" + "".join(f"   {s}\n" for s in symbols) + "\n"


def plan_pages(root, visibility: str) -> dict[str, str]:
    """Generated page skeletons by filename, without touching the filesystem."""
    pages = {}
    entries = []
    for package in root.findall("package"):
        name = package.get("name", "")
        if not re.fullmatch(r"[\w.$]*", name):
            raise ExtensionError(f"Java autodoc: invalid package name {name!r}")
        types = [
            t
            for t in root.findall("type")
            if t.get("package") == name and visible(t, visibility)
        ]
        if not types:
            continue
        filename = "package-" + (name or "default")
        entries.append((name, filename))
        title = name or "Default package"
        body = heading(title, "=")
        if name:
            body += f".. java:autopackage:: {name}\n\n"
        for kind, group in TYPE_GROUPS.items():
            symbols = [t.get("id") for t in types if t.get("kind") == kind]
            if symbols:
                body += heading(group, "-") + summary_table(symbols)
        body += ".. toctree::\n   :hidden:\n\n"
        for t in types:
            symbol = t.get("id")
            if not re.fullmatch(r"[\w.$]+", symbol):
                raise ExtensionError(f"Java autodoc: invalid type name {symbol!r}")
            typefile = "type-" + symbol
            body += f"   {typefile}\n"
            # Titles drop the package, which the sidebar and the signature already show.
            page = heading(local_name(t), "=") + f".. java:autoclass:: {symbol}\n\n"
            members = [m for m in t.findall("member") if visible(m, visibility)]
            for group, found in grouped(members).items():
                symbols = [m.get("id") for m in found]
                directive = "autofield" if group == "field" else "automethod"
                page += heading(MEMBER_GROUPS[group], "-") + summary_table(symbols)
                page += "".join(f".. java:{directive}:: {s}\n\n" for s in symbols)
            pages[typefile + ".rst"] = MARKER + page
        pages[filename + ".rst"] = MARKER + body
    named = [name for name, _ in entries if name]
    pages["index.rst"] = (
        MARKER
        + heading("Java API", "=")
        + (summary_table(named) if named else "")
        # The summary cannot list the unnamed package, so then the toctree shows.
        + (
            ".. toctree::\n   :hidden:\n\n"
            if len(named) == len(entries)
            else ".. toctree::\n\n"
        )
        + "".join(f"   {filename}\n" for _, filename in entries)
    )
    return pages


def publish_pages(directory: Path, pages: dict[str, str]) -> None:
    """Replaces previously published pages in ``directory`` with ``pages``.

    Edited or unowned files are never overwritten, and a manifest journals each
    publication so an interrupted build recovers on the next run.
    """
    manifest_path = directory / ".java-autodoc-manifest.json"
    try:
        old = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
        if not isinstance(old, dict):
            raise ValueError("expected a filename-to-hashes mapping")
        for filename, hashes in old.items():
            if isinstance(hashes, str):
                hashes = old[filename] = [hashes]
            if (
                Path(filename).name != filename
                or not filename.endswith(".rst")
                or not isinstance(hashes, list)
                or not hashes
                or any(
                    not isinstance(h, str) or not re.fullmatch(r"[0-9a-f]{64}", h)
                    for h in hashes
                )
            ):
                raise ValueError("invalid filename or content hash")
    except (OSError, ValueError) as exc:
        raise ExtensionError(
            f"Java autodoc: invalid generated-page manifest: {exc}"
        ) from exc
    # Check ownership before recording any new files as ours.
    for filename in old.keys() | pages.keys():
        path = directory / filename
        if path.exists() and hashlib.sha256(
            path.read_bytes()
        ).hexdigest() not in old.get(filename, []):
            raise ExtensionError(
                f"Java autodoc: refusing to overwrite edited or unowned page {path}; move your edits into a guide."
            )
    hashes = {
        name: hashlib.sha256(content.encode()).hexdigest()
        for name, content in pages.items()
    }
    pending = {name: set(values) for name, values in old.items()}
    for name, digest in hashes.items():
        pending.setdefault(name, set()).add(digest)
    # Journal both versions before any page changes, so an interrupted build can retry.
    atomic_write(
        manifest_path,
        json.dumps(
            {name: sorted(values) for name, values in sorted(pending.items())}
        ).encode(),
    )
    for filename, content in pages.items():
        atomic_write(directory / filename, content.encode())
    for filename in old.keys() - pages.keys():
        (directory / filename).unlink(missing_ok=True)
    atomic_write(manifest_path, json.dumps(hashes, indent=2, sort_keys=True).encode())
